#!/usr/bin/env python3
"""固定TTFから差し込み用の文字・GID・送り幅表を生成する（開発時のみfontToolsが必要）。"""
import argparse
import base64
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import struct
import unicodedata

ROOT = Path(__file__).resolve().parent.parent


def eligible(scalar):
    return (0 <= scalar < 0x10000 and not 0xD800 <= scalar <= 0xDFFF
            and not 0xFE00 <= scalar <= 0xFE0F and unicodedata.category(chr(scalar)) != "Cc")


def generate(font_path):
    lock = json.loads((ROOT / "third_party/pdfcpu.lock").read_text())
    checksum = hashlib.sha256(font_path.read_bytes()).hexdigest()
    if checksum != lock["font_sha256"]:
        raise SystemExit("TTF checksum does not match third_party/pdfcpu.lock.")
    from fontTools.ttLib import TTFont
    with TTFont(font_path) as font:
        if font["head"].unitsPerEm != 2048:
            raise SystemExit("Unexpected font unitsPerEm.")
        cmap = font.getBestCmap()
        gids = {c: font.getGlyphID(name) for c, name in cmap.items()}
        groups = defaultdict(list)
        for c, gid in gids.items():
            if gid != 0:
                groups[gid].append(c)
        shared = {c for group in groups.values() if len(group) > 1 for c in group}
        assert len(cmap) == 11741 and all(gids.values())
        assert sum(c >= 0x10000 for c in cmap) == 314
        assert sum(c < 0x10000 for c in cmap) == 11427
        assert shared == {0x02DC, 0x0303, 0x29FCE, 0x29FD7}
        assert gids[0x02DC] == gids[0x0303] == 1343
        assert not any(0xFE00 <= c <= 0xFE0F or unicodedata.category(chr(c)) == "Cc" for c in cmap)
        scalars = sorted(c for c in cmap if gids[c] != 0 and eligible(c) and c not in shared)
        assert len(scalars) == 11425
        assert sum(unicodedata.category(chr(c)) == "Mn" for c in scalars) == 33
        data = b"".join(struct.pack("<HHH", c, gids[c], font["hmtx"][cmap[c]][0] * 1000 // 2048)
                        for c in scalars)
    encoded = base64.b64encode(data).decode()
    lines = ["// <auto-generated />",
             "// BIZ UDPゴシック v1.051由来（SIL OFL 1.1）。scripts/fill-template-glyphs.pyで生成。",
             f"// font_sha256: {checksum}", f"// data_sha256: {hashlib.sha256(data).hexdigest()}",
             "// entries: 11425",
             "// Data: scalar昇順、1件6 byte: u16 scalar / u16 GID / u16 advance（little-endian）。",
             "// advance: hmtx advance * 1000 // 2048（1/1000 em単位、切り捨て）。",
             "using System.Buffers.Binary;", "", "namespace Amane.Pdf.Api;", "",
             "internal static class FillTemplateGlyphs", "{",
             "    private static readonly byte[] Glyphs = Convert.FromBase64String("]
    chunks = [encoded[i:i+100] for i in range(0, len(encoded), 100)]
    lines += [f'        "{chunk}"' + (" +" if i < len(chunks)-1 else ");") for i, chunk in enumerate(chunks)]
    lines += ["", "    internal static bool TryGet(int scalar, out ushort glyphId, out ushort advance)",
              "    {", "        var low = 0;", "        var high = Glyphs.Length / 6 - 1;",
              "        while (low <= high)", "        {", "            var mid = low + (high - low) / 2;",
              "            var entry = Glyphs.AsSpan(mid * 6, 6);",
              "            var value = BinaryPrimitives.ReadUInt16LittleEndian(entry);",
              "            if (scalar < value) high = mid - 1;",
              "            else if (scalar > value) low = mid + 1;", "            else", "            {",
              "                glyphId = BinaryPrimitives.ReadUInt16LittleEndian(entry[2..]);",
              "                advance = BinaryPrimitives.ReadUInt16LittleEndian(entry[4..]);",
              "                return true;", "            }", "        }",
              "        glyphId = advance = 0;", "        return false;", "    }", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ttf", type=Path)
    parser.add_argument("--check", action="store_true", help="再生成せず、コミット済みの表との一致を確認")
    args = parser.parse_args()
    path = ROOT / "src/Amane.Pdf.Api/FillTemplateGlyphs.g.cs"
    expected = generate(args.ttf).encode("utf-8")
    if args.check:
        if path.read_bytes() != expected:
            raise SystemExit("Fill template glyph table is stale.")
    else:
        path.write_bytes(expected)
    print(f"{'Verified' if args.check else 'Generated'} fill template glyph table: 11425 entries, 68550 bytes.")


if __name__ == "__main__":
    main()
