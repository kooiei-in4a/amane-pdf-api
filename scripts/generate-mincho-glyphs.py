#!/usr/bin/env python3
"""固定した明朝v1.06から、ゴシックと同じ規則で送り幅表を生成する。"""
import argparse
import base64
from collections import Counter
import hashlib
import importlib.util
from pathlib import Path
import struct

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_HASH = "dbcea04578ac1e9d3484525e870ce491bd04361768f4d2ba4b827d96e20f891d"
DATA_HASH = "ef285953c5be4369ae8789d803d4c07c8bdfb325d166cf258992972d8299f003"
spec = importlib.util.spec_from_file_location("gothic", ROOT / "scripts/fill-template-glyphs.py")
gothic = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gothic)


def generate(path):
    assert hashlib.sha256(path.read_bytes()).hexdigest() == FONT_HASH
    with TTFont(path) as font:
        units = font["head"].unitsPerEm
        assert units == 2048
        cmap = font.getBestCmap()
        gids = {code: font.getGlyphID(name) for code, name in cmap.items()}
        counts = Counter(gid for gid in gids.values() if gid)
        data = b"".join(struct.pack("<HHH", code, gid, font["hmtx"][cmap[code]][0] * 1000 // units)
                        for code, gid in sorted(gids.items()) if gid and counts[gid] == 1 and gothic.eligible(code))
    assert len(data) == 11425 * 6 and hashlib.sha256(data).hexdigest() == DATA_HASH
    source = (ROOT / "src/Amane.Pdf.Api/FillTemplateGlyphs.g.cs").read_text()
    declaration = "    private static readonly byte[] Glyphs = Convert.FromBase64String("
    tail = source.split(declaration, 1)[1].split(");", 1)[1]
    encoded = base64.b64encode(data).decode()
    lines = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    body = " +\n".join(f'        "{line}"' for line in lines)
    return f"""// <auto-generated />
// BIZ UDP明朝 v1.06 (SIL OFL 1.1). scripts/generate-mincho-glyphs.py
// font_sha256: {FONT_HASH}
// data_sha256: {DATA_HASH}
// entries: 11425
using System.Buffers.Binary;

namespace Amane.Pdf.Api;

internal static class MinchoGlyphs
{{
{declaration}
{body});{tail}"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ttf", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(args.ttf).encode()
    path = ROOT / "src/Amane.Pdf.Api/Compose/MinchoGlyphs.g.cs"
    if args.check:
        assert path.read_bytes() == expected
    else:
        path.write_bytes(expected)
