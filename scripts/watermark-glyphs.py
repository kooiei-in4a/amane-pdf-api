#!/usr/bin/env python3
"""固定TTFから透かし用の字形表を再生成する（開発時のみfontToolsが必要）。"""
import argparse
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RANGES = [(0x20, 0x7E), (0x3000, 0x30FF), (0x4E00, 0x9FFF), (0xFF01, 0xFF5E), (0xFF61, 0xFF9F)]


def generate(font_path):
    from fontTools.ttLib import TTFont
    lock = json.loads((ROOT / "third_party/pdfcpu.lock").read_text())
    checksum = hashlib.sha256(font_path.read_bytes()).hexdigest()
    if checksum != lock["font_sha256"]:
        raise SystemExit("TTF checksum does not match third_party/pdfcpu.lock.")
    with TTFont(font_path) as font:
        if font["head"].unitsPerEm != 2048:
            raise SystemExit("Unexpected font unitsPerEm.")
        cmap = font.getBestCmap()
        advances = [font["hmtx"][cmap[c]][0] for c in range(0x20, 0x7F)]
        scalars = [c for start, end in RANGES for c in range(start, end + 1)]
        bits = bytearray((len(scalars) + 7) // 8)
        for i, c in enumerate(scalars):
            if c in cmap and font.getGlyphID(cmap[c]) != 0:
                bits[i // 8] |= 1 << (i % 8)
    encoded = base64.b64encode(bits).decode()
    lines = ["// <auto-generated />", "// BIZ UDPゴシック v1.051由来（SIL OFL 1.1）。scripts/watermark-glyphs.pyで生成。",
             f"// font_sha256: {checksum}", "namespace Amane.Pdf.Api;", "", "internal static class WatermarkGlyphs", "{",
             "    internal static ReadOnlySpan<int> AsciiAdvances =>", "    ["]
    for i in range(0, len(advances), 12):
        lines.append("        " + ", ".join(map(str, advances[i:i+12])) + ",")
    lines += ["    ];", "", "    private static readonly byte[] Glyphs = Convert.FromBase64String("]
    chunks = [encoded[i:i+100] for i in range(0, len(encoded), 100)]
    lines += [f'        "{chunk}"' + (" +" if i < len(chunks)-1 else ");") for i, chunk in enumerate(chunks)]
    lines += ["", "    internal static bool Contains(int scalar)", "    {", "        var index = scalar switch", "        {"]
    offset = 0
    for start, end in RANGES:
        lines.append(f"            >= 0x{start:04x} and <= 0x{end:04x} => scalar - 0x{start:04x} + {offset},")
        offset += end - start + 1
    lines += ["            _ => -1", "        };", "        return index >= 0 && (Glyphs[index / 8] & (1 << (index % 8))) != 0;", "    }", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ttf", type=Path)
    parser.add_argument("--check", action="store_true", help="再生成せず、コミット済みの表との一致を確認")
    args = parser.parse_args()
    path = ROOT / "src/Amane.Pdf.Api/WatermarkGlyphs.g.cs"
    expected = generate(args.ttf)
    if args.check:
        if path.read_text() != expected:
            raise SystemExit("Watermark glyph table is stale.")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
